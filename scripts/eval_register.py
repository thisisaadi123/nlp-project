"""Register benchmark: does the translation pick the right form of address for the scene?

    python scripts/eval_register.py

Each case in data/register_cases.jsonl is one line whose correct translation depends on who
is speaking to whom (bhai vs bhaiya -> machan vs anna, aap vs tu, ...). Three setups:

  A  draft only         IndicTrans2 alone: a literal, context-blind translation
  B  LLM, no context    the refinement step without any scene information
  C  LLM, with context  the full step 4: scene, speakers and emotion

A case passes when every `expect` group has a match and no `forbid` term appears. The terms
were written by us, so the full outputs (with romanization) are also written to
docs/reports/step4-register-review.md for a native speaker to check.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.pipeline.translate.draft import translator  # noqa: E402
from backend.pipeline.translate.refine import FIT_HIGH, FIT_LOW, refine, syllables  # noqa: E402

CASES = ROOT / "data/register_cases.jsonl"
REVIEW = ROOT / "docs/reports/step4-register-review.md"
SETUPS = {"A": "draft only", "B": "LLM, no context", "C0": "C before length fit", "C": "LLM, with context"}


SEPARATORS = r"\s,.!?।'\"“”‘’"


def has(text: str, term: str) -> bool:
    """Substring match, or whole-word match for terms written as "=word" (short particles like
    Tamil "டா" also occur inside unrelated words, e.g. வேண்டாம்)."""
    if term.startswith("="):
        word = re.escape(term[1:])
        return re.search(rf"(?<![^{SEPARATORS}]){word}(?![^{SEPARATORS}])", text) is not None
    return term in text


def check(text: str, case: dict) -> tuple[bool, str]:
    missing = [g for g in case["expect"] if not any(has(text, term) for term in g)]
    found = [t.lstrip("=") for t in case["forbid"] if has(text, t)]
    reasons = [f"missing one of {'/'.join(g)}" for g in missing] + [f"contains {t}" for t in found]
    return not reasons, "; ".join(reasons)


def main() -> None:
    cases = [json.loads(line) for line in CASES.read_text(encoding="utf-8").splitlines() if line.strip()]
    draft_model = translator()
    results = []
    for i, case in enumerate(cases, 1):
        src_line = {"line_id": 1, **case["line"]}
        draft = draft_model.translate([src_line["text"]], case["src"], case["tgt"])[0]
        bare = {"line_id": 1, "text": src_line["text"], "emotion": src_line.get("emotion")}
        no_ctx = refine([bare], [draft], case["src"], case["tgt"], scene=None)[0]
        with_ctx = refine([src_line], [draft], case["src"], case["tgt"], scene=case["scene"])[0]
        before_fit = {"translation": with_ctx.get("fitted_from", with_ctx["translation"])}
        row = {"case": case, "A": {"translation": draft}, "B": no_ctx, "C0": before_fit, "C": with_ctx}
        for s in SETUPS:
            row[s]["pass"], row[s]["why"] = check(row[s]["translation"], case)
        results.append(row)
        marks = " ".join(f"{s}:{'✓' if row[s]['pass'] else '✗'}" for s in SETUPS)
        print(f"[{i:2d}/{len(cases)}] {case['id']}  {marks}  {with_ctx.get('romanized', '')}")

    print("\n== Register accuracy")
    print(f"{'setup':22s}{'all':>8s}{'hi→ta':>8s}{'ta→hi':>8s}")
    summary = {}
    for s, name in SETUPS.items():
        def rate(direction=None):
            rows = [r for r in results if direction is None or r["case"]["id"].startswith(direction)]
            return sum(r[s]["pass"] for r in rows) / len(rows)
        summary[s] = (rate(), rate("hi-ta"), rate("ta-hi"))
        print(f"{s:3s}{name:20s}{summary[s][0]:8.0%}{summary[s][1]:8.0%}{summary[s][2]:8.0%}")

    def in_range(text, source):
        return FIT_LOW <= syllables(text) / max(syllables(source), 1) <= FIT_HIGH
    before = sum(in_range(r["C"].get("fitted_from", r["C"]["translation"]), r["case"]["line"]["text"])
                 for r in results) / len(results)
    within = sum(in_range(r["C"]["translation"], r["case"]["line"]["text"]) for r in results) / len(results)
    rewritten = sum("fitted_from" in r["C"] for r in results)
    emph = [r for r in results if r["C"].get("emphasis")]
    emph_ok = sum(all(e.get("target_word", "") in r["C"]["translation"] for e in r["C"]["emphasis"]) for r in emph)
    print(f"\nC: length within {FIT_LOW:.0%}-{FIT_HIGH:.0%} of the source's syllables: "
          f"{before:.0%} before the fit pass, {within:.0%} after ({rewritten} lines rewritten)")
    print(f"C: emphasis target words present in the translation: {emph_ok}/{len(emph)}")
    write_review(results, summary, within)
    print(f"\nFull outputs for native-speaker review: {REVIEW.relative_to(ROOT)}")


def write_review(results, summary, within) -> None:
    out = ["# Step 4 register benchmark: outputs for review", "",
           "Generated by `scripts/eval_register.py`. A = IndicTrans2 draft, B = LLM without scene "
           "context, C = LLM with scene context. ✓/✗ is the automatic check against the expected "
           "address terms; a native speaker should confirm C reads naturally.", "",
           "| Setup | All | hi→ta | ta→hi |", "|---|---|---|---|"]
    for s, name in SETUPS.items():
        a, h, t = summary[s]
        out.append(f"| {s}. {name} | {a:.0%} | {h:.0%} | {t:.0%} |")
    out += ["", f"C keeps the length within {FIT_LOW:.0%}-{FIT_HIGH:.0%} of the source's syllables for {within:.0%} of lines.", ""]
    for r in results:
        c = r["case"]
        out += [f"## {c['id']}: {c['note']}", "",
                f"**Scene:** {c['scene']['relationship']} ({c['scene']['setting']}). "
                f"**Emotion:** {c['line']['emotion']['label']}", "",
                f"**Source:** {c['line']['text']}", ""]
        for s, name in SETUPS.items():
            res = r[s]
            mark = "✓" if res["pass"] else f"✗ ({res['why']})"
            roman = f"  \n  *{res['romanized']}*" if res.get("romanized") else ""
            out.append(f"- **{s}. {name}** {mark}: {res['translation']}{roman}")
        if r["C"].get("delivery"):
            out.append(f"- **Delivery note (C):** {r['C']['delivery']}")
        out.append("")
    REVIEW.parent.mkdir(parents=True, exist_ok=True)
    REVIEW.write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
